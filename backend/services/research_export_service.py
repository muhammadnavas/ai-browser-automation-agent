"""
services/research_export_service.py
-----------------------------------
Structured multi-format report export service for multi-website research results.

Supports:
- CSV: RFC 4180 compliant with formula injection protection and clear headers.
- XLSX: Multi-sheet styled Excel workbook with evidence and status auditing.
- PDF: Clean, publication-ready comparison matrix and source attribution using fpdf2.

Sanitizes spreadsheet values against formula injection (CWE-1236).
"""

import csv
import io
import logging
from typing import Any, List
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
from fpdf import FPDF

from models.schemas import ComparisonResult

logger = logging.getLogger("services.research_export_service")


def sanitize_spreadsheet_value(val: Any) -> Any:
    """
    Sanitize values to prevent formula injection in CSV / Excel (CWE-1236).
    Prepends a single quote if a string begins with dangerous prefix characters.
    """
    if val is None:
        return "N/A"
    if isinstance(val, (int, float, bool)):
        return val

    s = str(val)
    if not s:
        return ""
    if s[0] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + s
    stripped = s.strip()
    if stripped and stripped[0] in ("=", "+", "-", "@"):
        return "'" + s
    return s


class ResearchPDFReport(FPDF):
    """Clean PDF layout for research reports using Helvetica core font."""

    def header(self):
        self.set_text_color(31, 48, 74)
        self.set_font("Helvetica", "B", 13)
        self.cell(0, 8, "AI BROWSER AGENT  |  MULTI-WEBSITE RESEARCH REPORT", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(100, 110, 125)
        self.set_font("Helvetica", "", 8)
        self.cell(0, 4, "Structured Competitive Analysis & Comparison", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(210, 220, 230)
        self.line(self.l_margin, self.get_y() + 2, self.w - self.r_margin, self.get_y() + 2)
        self.ln(6)

    def footer(self):
        self.set_y(-12)
        self.set_draw_color(220, 226, 234)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.set_y(-10)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(120, 130, 145)
        self.cell(0, 6, f"Generated by AI Browser Agent  |  Page {self.page_no()}", align="C")


class ResearchExportService:
    """Exports ComparisonResult into CSV, XLSX, and PDF formats."""

    @staticmethod
    def export_csv(comparison: ComparisonResult) -> bytes:
        """
        Generate RFC 4180 compliant CSV bytes.
        Applies formula injection sanitization to all cell values.
        """
        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

        criteria = comparison.criteria or []
        headers = ["Record ID", "Entity Name"] + criteria + ["Source URLs", "Duplicate Across Sources", "Conflicts Flagged"]
        writer.writerow(headers)

        for rec in comparison.records:
            row: List[Any] = [
                sanitize_spreadsheet_value(rec.record_id),
                sanitize_spreadsheet_value(rec.name),
            ]
            for crit in criteria:
                val = rec.fields.get(crit, "N/A")
                row.append(sanitize_spreadsheet_value(val))

            sources_str = "; ".join(rec.source_urls) if rec.source_urls else "N/A"
            row.append(sanitize_spreadsheet_value(sources_str))
            row.append("Yes" if rec.is_duplicate_across_sources else "No")

            if rec.conflicts:
                conflict_desc = " | ".join(c.description for c in rec.conflicts)
                row.append(sanitize_spreadsheet_value(conflict_desc))
            else:
                row.append("None")

            writer.writerow(row)

        return output.getvalue().encode("utf-8")

    @staticmethod
    def export_xlsx(comparison: ComparisonResult) -> bytes:
        """
        Generate a multi-sheet Excel workbook.
        Sheet 1: Comparison Matrix
        Sheet 2: Detailed Evidence & Attribution
        Sheet 3: Source Status Audit
        """
        wb = Workbook()

        # Styles
        header_fill = PatternFill(start_color="1F304A", end_color="1F304A", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        title_font = Font(name="Calibri", size=14, bold=True, color="1F304A")
        sub_font = Font(name="Calibri", size=10, italic=True, color="555555")
        bold_font = Font(name="Calibri", size=10, bold=True)
        regular_font = Font(name="Calibri", size=10)
        thin_border = Border(
            left=Side(style="thin", color="E0E0E0"),
            right=Side(style="thin", color="E0E0E0"),
            top=Side(style="thin", color="E0E0E0"),
            bottom=Side(style="thin", color="E0E0E0"),
        )
        align_left = Alignment(horizontal="left", vertical="center", wrap_text=True)
        align_center = Alignment(horizontal="center", vertical="center")

        # ── Sheet 1: Comparison Summary ─────────────────────────────────
        ws1 = wb.active
        ws1.title = "Comparison Summary"

        ws1.append(["Multi-Website Research & Comparison Report"])
        ws1.append([f"Goal: {comparison.goal}"])
        ws1.append([f"Criteria: {', '.join(comparison.criteria) if comparison.criteria else 'Standard Extraction'}"])
        ws1.append([])

        ws1["A1"].font = title_font
        ws1["A2"].font = sub_font
        ws1["A3"].font = sub_font

        criteria = comparison.criteria or []
        headers = ["Record ID", "Entity Name"] + criteria + ["Source URLs", "Duplicate Across Sources", "Conflicts Flagged"]
        ws1.append(headers)
        header_row_idx = ws1.max_row

        for col_idx in range(1, len(headers) + 1):
            cell = ws1.cell(row=header_row_idx, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = align_center

        for rec in comparison.records:
            row_data = [
                sanitize_spreadsheet_value(rec.record_id),
                sanitize_spreadsheet_value(rec.name),
            ]
            for crit in criteria:
                val = rec.fields.get(crit, "N/A")
                row_data.append(sanitize_spreadsheet_value(val))

            sources_str = ", ".join(rec.source_urls) if rec.source_urls else "N/A"
            row_data.append(sanitize_spreadsheet_value(sources_str))
            row_data.append("Yes" if rec.is_duplicate_across_sources else "No")

            if rec.conflicts:
                conflict_desc = " | ".join(c.description for c in rec.conflicts)
                row_data.append(sanitize_spreadsheet_value(conflict_desc))
            else:
                row_data.append("None")

            ws1.append(row_data)
            curr_row = ws1.max_row
            for col_idx in range(1, len(row_data) + 1):
                c = ws1.cell(row=curr_row, column=col_idx)
                c.font = regular_font
                c.border = thin_border
                c.alignment = align_left

        # Adjust column widths
        for col in ws1.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws1.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 40)

        # ── Sheet 2: Detailed Evidence & Attribution ────────────────────
        ws2 = wb.create_sheet(title="Source Evidence")
        evidence_headers = ["Record ID", "Entity Name", "Field", "Value", "Source URL", "Confidence", "Evidence Snippet"]
        ws2.append(evidence_headers)
        for col_idx in range(1, len(evidence_headers) + 1):
            cell = ws2.cell(row=1, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = align_center

        for rec in comparison.records:
            for field_name, ev in rec.evidence.items():
                ev_row = [
                    sanitize_spreadsheet_value(rec.record_id),
                    sanitize_spreadsheet_value(rec.name),
                    sanitize_spreadsheet_value(field_name),
                    sanitize_spreadsheet_value(ev.value),
                    sanitize_spreadsheet_value(ev.source_url),
                    f"{ev.confidence:.0%}" if ev.confidence else "N/A",
                    sanitize_spreadsheet_value(ev.evidence_text or "Direct page content"),
                ]
                ws2.append(ev_row)
                curr_row = ws2.max_row
                for col_idx in range(1, len(ev_row) + 1):
                    c = ws2.cell(row=curr_row, column=col_idx)
                    c.font = regular_font
                    c.border = thin_border
                    c.alignment = align_left

        for col in ws2.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws2.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 45)

        # ── Sheet 3: Sources Audited ────────────────────────────────────
        ws3 = wb.create_sheet(title="Sources Audited")
        status_headers = ["Source URL", "Status", "Page Title", "Extracted Fields", "Duration (ms)", "Error Details"]
        ws3.append(status_headers)
        for col_idx in range(1, len(status_headers) + 1):
            cell = ws3.cell(row=1, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = align_center

        for src in comparison.sources:
            src_row = [
                sanitize_spreadsheet_value(src.url),
                src.status.upper(),
                sanitize_spreadsheet_value(src.title or "N/A"),
                src.extracted_fields_count,
                round(src.duration_ms, 1) if src.duration_ms else "N/A",
                sanitize_spreadsheet_value(src.error or "None"),
            ]
            ws3.append(src_row)
            curr_row = ws3.max_row
            for col_idx in range(1, len(src_row) + 1):
                c = ws3.cell(row=curr_row, column=col_idx)
                c.font = regular_font
                c.border = thin_border
                c.alignment = align_left

        for col in ws3.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws3.column_dimensions[col_letter].width = min(max(max_len + 3, 14), 50)

        stream = io.BytesIO()
        wb.save(stream)
        return stream.getvalue()

    @staticmethod
    def export_pdf(comparison: ComparisonResult) -> bytes:
        """
        Generate a PDF comparison document with table layout,
        source attribution, and conflict flagging using fpdf2.
        """
        pdf = ResearchPDFReport(orientation="L", unit="mm", format="A4")
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        # Metadata Section
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(31, 48, 74)
        pdf.set_x(pdf.l_margin)
        pdf.cell(pdf.epw, 6, "Research Executive Summary", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)

        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(50, 60, 75)
        goal_text = comparison.goal.encode("latin-1", errors="replace").decode("latin-1")
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(pdf.epw, 5, f"Research Goal: {goal_text}", new_x="LMARGIN", new_y="NEXT")

        criteria_str = ", ".join(comparison.criteria) if comparison.criteria else "General Attributes"
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(pdf.epw, 5, f"Comparison Criteria: {criteria_str}", new_x="LMARGIN", new_y="NEXT")

        total_sources = len(comparison.sources)
        completed_sources = sum(1 for s in comparison.sources if s.status == "completed")
        failed_sources = sum(1 for s in comparison.sources if s.status == "failed")
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(pdf.epw, 5, f"Sources Evaluated: {total_sources} total ({completed_sources} successful, {failed_sources} failed)", new_x="LMARGIN", new_y="NEXT")
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(pdf.epw, 5, f"Total Unique Records Identified: {len(comparison.records)}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

        # Comparison Table
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(31, 48, 74)
        pdf.set_x(pdf.l_margin)
        pdf.cell(pdf.epw, 6, "Structured Comparison Matrix", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

        criteria = comparison.criteria[:4] if comparison.criteria else []  # Fit comfortably on landscape
        cols = ["Record Name"] + criteria + ["Sources", "Status"]

        name_w = 60.0
        crit_w = 38.0 if criteria else 0.0
        src_w = 50.0
        status_w = 25.0
        remaining_w = pdf.epw - (name_w + src_w + status_w + (len(criteria) * crit_w))
        if remaining_w > 0:
            name_w += remaining_w / 2
            src_w += remaining_w / 2

        def _draw_matrix_header():
            pdf.set_x(pdf.l_margin)
            pdf.set_fill_color(31, 48, 74)
            pdf.set_text_color(255, 255, 255)
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(name_w, 7, "Entity Name", border=1, fill=True)
            for crit in criteria:
                pdf.cell(crit_w, 7, crit.capitalize()[:16], border=1, fill=True)
            pdf.cell(src_w, 7, "Source Attribution", border=1, fill=True)
            pdf.cell(status_w, 7, "Conflicts", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

        _draw_matrix_header()

        # Table Rows
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(40, 45, 55)
        for rec in comparison.records:
            if pdf.get_y() > 180:
                pdf.add_page()
                _draw_matrix_header()
                pdf.set_font("Helvetica", "", 8)
                pdf.set_text_color(40, 45, 55)

            pdf.set_x(pdf.l_margin)
            rec_name = rec.name[:35].encode("latin-1", errors="replace").decode("latin-1")
            pdf.cell(name_w, 6, rec_name, border=1)

            for crit in criteria:
                val = str(rec.fields.get(crit, "N/A"))[:20]
                val_safe = val.encode("latin-1", errors="replace").decode("latin-1")
                pdf.cell(crit_w, 6, val_safe, border=1)

            sources_summary = f"{len(rec.source_urls)} source(s)"
            if rec.is_duplicate_across_sources:
                sources_summary += " (deduped)"
            pdf.cell(src_w, 6, sources_summary, border=1)

            has_conflict = "FLAGGED" if rec.conflicts else "Clean"
            if rec.conflicts:
                pdf.set_text_color(180, 40, 40)
            else:
                pdf.set_text_color(40, 130, 60)
            pdf.cell(status_w, 6, has_conflict, border=1, new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(40, 45, 55)

        pdf.ln(5)

        # Flagged Conflicts Section (if any)
        conflicts_exist = any(rec.conflicts for rec in comparison.records)
        if conflicts_exist:
            pdf.set_x(pdf.l_margin)
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(180, 40, 40)
            pdf.cell(pdf.epw, 6, "Flagged Data Inconsistencies Across Sources:", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(50, 60, 75)
            for rec in comparison.records:
                for conf in rec.conflicts:
                    desc_safe = conf.description.encode("latin-1", errors="replace").decode("latin-1")
                    pdf.set_x(pdf.l_margin)
                    pdf.multi_cell(pdf.epw, 4, f"- [{rec.name[:30]}] {desc_safe}", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(3)

        # Sources Audit Table
        if pdf.get_y() > 170:
            pdf.add_page()

        pdf.set_x(pdf.l_margin)
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(31, 48, 74)
        pdf.cell(pdf.epw, 6, "Sources Status & Audit Log", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)

        src_status_w = 28.0
        src_fields_w = 28.0
        src_dur_w = 55.0
        src_url_w = pdf.epw - (src_status_w + src_fields_w + src_dur_w)

        pdf.set_x(pdf.l_margin)
        pdf.set_fill_color(240, 243, 246)
        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(src_url_w, 6, "Source URL", border=1, fill=True)
        pdf.cell(src_status_w, 6, "Status", border=1, fill=True)
        pdf.cell(src_fields_w, 6, "Fields Extracted", border=1, fill=True)
        pdf.cell(src_dur_w, 6, "Duration / Error", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 7)
        for src in comparison.sources:
            pdf.set_x(pdf.l_margin)
            url_safe = src.url[:85].encode("latin-1", errors="replace").decode("latin-1")
            pdf.cell(src_url_w, 5, url_safe, border=1)
            pdf.cell(src_status_w, 5, src.status.upper(), border=1)
            pdf.cell(src_fields_w, 5, str(src.extracted_fields_count), border=1)
            dur = f"{src.duration_ms:.0f}ms" if src.duration_ms else (src.error or "None")[:30]
            dur_safe = dur.encode("latin-1", errors="replace").decode("latin-1")
            pdf.cell(src_dur_w, 5, dur_safe, border=1, new_x="LMARGIN", new_y="NEXT")

        return bytes(pdf.output())
