"""Redis-backed semantic cache for reusable high-level browser task plans.

This deliberately uses Redis' basic key/value and SCAN operations rather than
requiring the Redis Search module. Similarity comparisons are scoped by agent
version, normalized start URL, and task intent to reduce unsafe reuse.
"""
from __future__ import annotations

import hashlib
import logging
import math
import os
from typing import Any, Awaitable, Callable, Dict, List, Optional

from services.cache_service import CacheService

logger = logging.getLogger("services.semantic_plan_cache")
EmbeddingFn = Callable[[str], Awaitable[Optional[List[float]]]]


class SemanticPlanCache:
    """Semantic plan cache using embeddings generated by a configured provider."""

    def __init__(
        self,
        cache_service: CacheService,
        embedding_fn: EmbeddingFn,
        *,
        threshold: Optional[float] = None,
        ttl_seconds: Optional[int] = None,
        max_candidates: Optional[int] = None,
    ) -> None:
        self.cache_service = cache_service
        self.embedding_fn = embedding_fn
        self.threshold = float(threshold if threshold is not None else os.getenv("SEMANTIC_CACHE_THRESHOLD", "0.92"))
        self.ttl_seconds = int(ttl_seconds if ttl_seconds is not None else os.getenv("SEMANTIC_CACHE_TTL", "1800"))
        self.max_candidates = max(1, int(max_candidates if max_candidates is not None else os.getenv("SEMANTIC_CACHE_MAX_CANDIDATES", "100")))
        self.enabled = os.getenv("SEMANTIC_CACHE_ENABLED", "true").strip().lower() not in ("0", "false", "no", "off")

    @staticmethod
    def cosine_similarity(left: List[float], right: List[float]) -> float:
        if not left or len(left) != len(right):
            return 0.0
        dot = sum(a * b for a, b in zip(left, right))
        left_norm = math.sqrt(sum(a * a for a in left))
        right_norm = math.sqrt(sum(b * b for b in right))
        if not left_norm or not right_norm:
            return 0.0
        return dot / (left_norm * right_norm)

    def _namespace(self, agent_version: str, url: str, intent: str) -> str:
        url_hash = hashlib.sha256(url.encode("utf-8")).hexdigest()[:20]
        intent_hash = hashlib.sha256(intent.encode("utf-8")).hexdigest()[:12]
        return f"{self.cache_service.key_prefix}:semantic_plan:{agent_version}:{url_hash}:{intent_hash}:"

    async def find(
        self,
        goal: str,
        start_url: str,
        agent_version: str,
        intent: str,
    ) -> Optional[Dict[str, Any]]:
        """Return the closest validated plan above the configured threshold."""
        if not self.enabled or not goal or not self.cache_service:
            return None
        # Do not send or persist goals containing values caught by the existing
        # sensitive-data redactor. Exact-match caching remains available.
        safe_goal = self.cache_service.sanitize_string(goal)
        if safe_goal != goal:
            logger.info("Semantic plan cache skipped: goal contains sensitive-looking data")
            return None
        try:
            query_vector = await self.embedding_fn(safe_goal)
            if not query_vector:
                return None
            normalized_url = self.cache_service.normalize_url(start_url)
            namespace = self._namespace(agent_version.strip().lower(), normalized_url, intent)
            client = await self.cache_service._get_client()
            if client is None:
                return None

            best: Optional[Dict[str, Any]] = None
            best_score = 0.0
            scanned = 0
            async for raw_key in client.scan_iter(match=f"{namespace}*", count=100):
                key = raw_key.decode("utf-8") if isinstance(raw_key, bytes) else str(raw_key)
                entry = await self.cache_service.get(key)
                if not isinstance(entry, dict):
                    continue
                vector = entry.get("embedding")
                if not isinstance(vector, list):
                    continue
                score = self.cosine_similarity(query_vector, vector)
                if score > best_score:
                    best_score, best = score, entry
                scanned += 1
                if scanned >= self.max_candidates:
                    break

            if best is not None and best_score >= self.threshold:
                plan = best.get("plan")
                if isinstance(plan, list) and plan and all(isinstance(step, str) and step.strip() for step in plan):
                    logger.info("Semantic plan cache HIT: similarity=%.4f threshold=%.4f", best_score, self.threshold)
                    return {
                        "plan": plan,
                        "source": best.get("source", "semantic"),
                        "metadata": best.get("metadata", {}),
                        "similarity": round(best_score, 4),
                        "matched_goal": best.get("goal", ""),
                    }
            logger.info("Semantic plan cache MISS: candidates=%s best_similarity=%.4f", scanned, best_score)
        except Exception as exc:
            logger.warning("Semantic plan cache lookup failed (non-fatal): %s", exc)
        return None

    async def store(
        self,
        goal: str,
        start_url: str,
        agent_version: str,
        intent: str,
        plan: List[str],
        source: str,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> bool:
        if not self.enabled or not goal or not plan or not self.cache_service:
            return False
        safe_goal = self.cache_service.sanitize_string(goal)
        if safe_goal != goal:
            logger.info("Semantic plan cache write skipped: goal contains sensitive-looking data")
            return False
        try:
            vector = await self.embedding_fn(safe_goal)
            if not vector:
                return False
            normalized_url = self.cache_service.normalize_url(start_url)
            namespace = self._namespace(agent_version.strip().lower(), normalized_url, intent)
            goal_hash = hashlib.sha256(safe_goal.encode("utf-8")).hexdigest()
            key = f"{namespace}{goal_hash}"
            payload = {
                "goal": safe_goal,
                "url": normalized_url,
                "agent_version": agent_version.strip().lower(),
                "intent": intent,
                "embedding": vector,
                "plan": [str(step) for step in plan],
                "source": source,
                "metadata": metadata or {},
            }
            return await self.cache_service.set(key, payload, ttl=self.ttl_seconds)
        except Exception as exc:
            logger.warning("Semantic plan cache write failed (non-fatal): %s", exc)
            return False
