import json
import logging
import os
import time
from datetime import datetime
from typing import Any, Optional
from urllib.parse import urlsplit

from fpdf import FPDF

logger = logging.getLogger("ReportGenerator")


class PDFReport(FPDF):
    """Shared report chrome and page numbering."""

    def header(self):
        # Compact fixed-height brand strip; position content explicitly so the
        # header never leaves an oversized blank gap before the report body.
        self.set_fill_color(7, 18, 13)
        self.rect(0, 0, self.w, 24, style="F")
        self.set_xy(self.l_margin, 5)
        self.set_text_color(101, 230, 164)
        self.set_font("Helvetica", "B", 13)
        self.cell(0, 7, "AUTOMATA", new_x="LMARGIN", new_y="NEXT")
        self.set_x(self.l_margin)
        self.set_text_color(185, 205, 193)
        self.set_font("Helvetica", "", 7.5)
        self.cell(0, 4, "TASK EXECUTION REPORT", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(48, 116, 81)
        self.line(self.l_margin, 24, self.w - self.r_margin, 24)
        self.set_y(29)
        self.set_text_color(31, 48, 40)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(48, 116, 81)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.set_y(-11)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(91, 112, 100)
        self.cell(0, 6, f"Generated by Automata  |  Page {self.page_no()}", align="C")


class ReportGenerator:
    """Generate a structured, readable PDF report for a browser-automation task."""

    def __init__(self, output_dir: Optional[str] = None):
        self.output_dir = output_dir
        logger.info("PDF report generator ready (in-memory mode)")

    @staticmethod
    def _safe_text(value: Any) -> str:
        """Keep arbitrary task text compatible with FPDF's built-in fonts."""
        if value is None:
            return ""
        return str(value).encode("latin-1", errors="replace").decode("latin-1")

    @staticmethod
    def _status(task: Any) -> str:
        status = getattr(task, "status", "unknown")
        return str(status.value if hasattr(status, "value") else status).upper()

    @staticmethod
    def _safe_url(value: Any) -> str:
        """Omit query strings and fragments that may contain private page state."""
        if not value:
            return ""
        try:
            parts = urlsplit(str(value))
            if parts.scheme and parts.netloc:
                return f"{parts.scheme}://{parts.netloc}{parts.path}"
        except Exception:
            pass
        return str(value).split("?", 1)[0].split("#", 1)[0]

    @staticmethod
    def _resolve_screenshot_path(step: Any) -> Optional[str]:
        path = getattr(step, "screenshot_path", None)
        screenshot_url = getattr(step, "screenshot_url", None)
        if not path and screenshot_url:
            for prefix in ("/api/download/screenshots/", "/api/screenshots/"):
                if screenshot_url.startswith(prefix):
                    path = os.path.join("screenshots", os.path.basename(screenshot_url))
                    break
        if path and os.path.isfile(path):
            return path
        if path:
            candidate = os.path.join("screenshots", os.path.basename(path))
            if os.path.isfile(candidate):
                return candidate
        return None

    def _section(self, pdf: PDFReport, title: str, subtitle: Optional[str] = None) -> None:
        if pdf.get_y() > pdf.h - 35:
            pdf.add_page()
        pdf.ln(1)
        pdf.set_fill_color(10, 31, 22)
        pdf.set_text_color(101, 230, 164)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 6.5, self._safe_text(title), new_x="LMARGIN", new_y="NEXT", fill=True)
        if subtitle:
            pdf.set_text_color(106, 128, 115)
            pdf.set_font("Helvetica", "", 7.5)
            self._paragraph(pdf, subtitle, 3.6)
        pdf.set_text_color(31, 48, 40)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.ln(0.8)

    def _paragraph(self, pdf: PDFReport, value: Any, line_height: float = 4.5) -> None:
        """Render wrapped text using FPDF's native multi_cell and safe page boundaries."""
        if value is None or str(value).strip() == "":
            return
        text = self._safe_text(value).replace("\r\n", "\n").replace("\r", "\n")
        usable_width = pdf.w - pdf.l_margin - pdf.r_margin
        for paragraph in text.split("\n"):
            paragraph_str = paragraph.strip()
            if not paragraph_str:
                if pdf.get_y() + line_height > pdf.h - pdf.b_margin:
                    pdf.add_page()
                pdf.ln(line_height)
                continue
            if pdf.get_y() + line_height > pdf.h - pdf.b_margin:
                pdf.add_page()
            pdf.set_x(pdf.l_margin)
            pdf.multi_cell(usable_width, line_height, paragraph_str, new_x="LMARGIN", new_y="NEXT")

    def _key_value(self, pdf: PDFReport, label: str, value: Any) -> None:
        """Render compact two-column metadata with safe wrapping and page breaks."""
        if value is None or str(value).strip() == "":
            return

        line_height = 4.5
        label_width = 36
        value_width = pdf.w - pdf.l_margin - pdf.r_margin - label_width
        rendered = self._safe_text(value).replace("\r\n", "\n").replace("\r", "\n")
        # Estimate enough room for at least the first row. FPDF's auto page
        # break handles additional wrapped lines.
        if pdf.get_y() > pdf.h - pdf.b_margin - 12:
            pdf.add_page()

        start_y = pdf.get_y()
        pdf.set_xy(pdf.l_margin, start_y)
        pdf.set_font("Helvetica", "B", 8.5)
        pdf.set_text_color(65, 105, 80)
        pdf.cell(label_width, line_height, self._safe_text(f"{label}:"), new_x="RIGHT", new_y="TOP")

        pdf.set_xy(pdf.l_margin + label_width, start_y)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(31, 48, 40)
        pdf.multi_cell(
            value_width,
            line_height,
            rendered,
            new_x="LMARGIN",
            new_y="NEXT",
        )
        pdf.ln(0.3)

    def _data_block(self, pdf: PDFReport, data: Any) -> None:
        rendered = self._sanitize_step_data(data)
        try:
            rendered = json.dumps(json.loads(rendered), indent=2, ensure_ascii=False, default=str)
        except Exception:
            pass
        pdf.set_font("Courier", "", 8)
        pdf.set_text_color(25, 40, 30)
        self._paragraph(pdf, rendered, 3.8)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(31, 48, 40)

    def generate_report(self, task_id: str, task: Any) -> bytes:
        """Generate a professional PDF report for a terminal task and return it as bytes."""
        started = time.perf_counter()
        try:
            pdf = PDFReport(orientation="P", unit="mm", format="A4")
            pdf.set_margins(14, 29, 14)
            pdf.set_auto_page_break(auto=True, margin=14)
            pdf.add_page()

            status = self._status(task)
            steps = list(getattr(task, "steps", []) or [])
            failed_steps = sum(1 for step in steps if getattr(step, "error", None))
            approval_steps_from_steps = sum(
                1 for step in steps
                if getattr(step, "approval_required", False)
                or getattr(step, "human_intervention_needed", False)
                or str(getattr(step, "action", "")).lower().endswith("request_approval")
            )
            # Approval requests are cleared after the user responds, so count
            # them from the durable task counter rather than the transient
            # approval_request object. Fall back to step metadata for older tasks.
            approval_steps = max(
                int(getattr(task, "human_approval_count", 0) or 0),
                approval_steps_from_steps,
            )
            created_at = getattr(task, "created_at", None)
            updated_at = getattr(task, "updated_at", None)
            duration = max(0, updated_at - created_at) if created_at and updated_at else None
            duration_text = (
                f"{duration / 60:.1f} min" if duration is not None and duration >= 60
                else f"{duration:.1f} sec" if duration is not None else "Not recorded"
            )

            # Report title and status banner
            pdf.set_font("Helvetica", "B", 17)
            pdf.set_text_color(12, 52, 32)
            pdf.cell(0, 9, "Execution Overview", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(91, 112, 100)
            pdf.cell(0, 4.5, self._safe_text(f"Task {task_id}  |  Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}"), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1.5)

            status_colors = {
                "COMPLETED": (220, 250, 233, 15, 105, 57),
                "FAILED": (255, 232, 232, 155, 35, 45),
                "CANCELLED": (255, 242, 219, 140, 85, 15),
                "RUNNING": (222, 248, 232, 20, 105, 65),
                "PENDING": (233, 242, 236, 55, 85, 65),
                "WAITING_APPROVAL": (255, 242, 219, 140, 85, 15),
                "PAUSED": (255, 247, 220, 125, 90, 15),
            }
            bg_r, bg_g, bg_b, fg_r, fg_g, fg_b = status_colors.get(status, (238, 242, 247, 75, 85, 100))
            pdf.set_fill_color(bg_r, bg_g, bg_b)
            pdf.set_text_color(fg_r, fg_g, fg_b)
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 7, self._safe_text(f"  STATUS: {status}"), new_x="LMARGIN", new_y="NEXT", fill=True)
            pdf.set_text_color(35, 43, 55)
            pdf.ln(1)

            self._section(pdf, "Task Details")
            self._key_value(pdf, "Goal", getattr(task, "goal", ""))
            self._key_value(pdf, "Task ID", task_id)
            self._key_value(pdf, "Started", datetime.fromtimestamp(created_at).strftime("%Y-%m-%d %H:%M:%S") if created_at else "Not recorded")
            self._key_value(pdf, "Finished / updated", datetime.fromtimestamp(updated_at).strftime("%Y-%m-%d %H:%M:%S") if updated_at else "Not recorded")
            self._key_value(pdf, "Total duration", duration_text)
            self._key_value(pdf, "Recorded steps", len(steps))
            self._key_value(pdf, "Steps with errors", failed_steps)
            self._key_value(pdf, "Human approval steps", approval_steps)
            err_lower = str(getattr(task, "error", "") or "").lower()
            is_transient_approval_msg = any(
                w in err_lower
                for w in ["approval", "approved", "recovering", "browser session"]
            )
            if getattr(task, "error", None) and status != "COMPLETED" and not is_transient_approval_msg:
                pdf.set_text_color(160, 25, 25)
                self._key_value(pdf, "Task error", self._sanitize_decision_explanation(task.error))
                pdf.set_text_color(35, 43, 55)

            # State clearly what the report can and cannot conclude.
            self._section(pdf, "Outcome")
            pdf.set_font("Helvetica", "", 8.5)
            pdf.set_text_color(31, 48, 40)
            if status == "COMPLETED":
                self._paragraph(pdf, "The task manager reported this task as completed. Review the execution evidence below for the actions and observed page states.", 4.5)
            elif status == "FAILED":
                self._paragraph(pdf, "The task failed. The error and failed steps, when available, are listed below.", 5)
            elif status == "CANCELLED":
                self._paragraph(pdf, "The task was cancelled before normal completion.", 5)
            else:
                self._paragraph(pdf, f"The task status at report generation was {status}. Do not interpret this report as proof of successful completion.", 5)

            extracted_data = getattr(task, "extracted_data", None)
            if extracted_data:
                self._section(pdf, "Results / Extracted Data")
                self._data_block(pdf, extracted_data)

            context = getattr(task, "context", None)
            visited_urls = list(getattr(context, "visited_urls", []) or [])
            if visited_urls:
                self._section(pdf, "Visited Pages")
                pdf.set_font("Helvetica", "", 8.5)
                pdf.set_text_color(35, 75, 55)
                for visited_url in visited_urls[-20:]:
                    self._paragraph(pdf, self._safe_url(visited_url), 4.5)

            plan = getattr(task, "initial_plan", None) or []
            if plan:
                self._section(pdf, "Planned Workflow")
                for index, item in enumerate(plan, start=1):
                    # Render the number and description as one wrapped paragraph.
                    # The previous inline cell advanced the cursor, then
                    # _paragraph reset to the left margin and overprinted it.
                    pdf.set_font("Helvetica", "", 9)
                    pdf.set_text_color(31, 48, 40)
                    self._paragraph(pdf, f"{index:02d}.  {item}", 5)

            # Show plan evolution as distinct, readable version cards so a
            # reviewer can compare the original plan with each later replan.
            plan_metadata = getattr(task, "plan_metadata", None) or {}
            plan_versions = plan_metadata.get("plan_versions", []) if isinstance(plan_metadata, dict) else []
            if isinstance(plan_versions, list) and plan_versions:
                self._section(
                    pdf,
                    "Plan Version History",
                    "Each version records the plan produced at that point in the task.",
                )
                current_version = plan_metadata.get("plan_version")
                if current_version is None:
                    current_version = plan_versions[-1].get("version", len(plan_versions)) if isinstance(plan_versions[-1], dict) else len(plan_versions)

                reason_labels = {
                    "initial_plan": "Initial plan",
                    "live_page_inspection": "Refined after live page inspection",
                    "adaptive_replan": "Adaptive replan during execution",
                    "recovery": "Recovery replan",
                }

                for index, version in enumerate(plan_versions, start=1):
                    if not isinstance(version, dict):
                        continue

                    version_number = version.get("version", index)
                    is_current = str(version_number) == str(current_version)
                    milestones = version.get("milestones") or []
                    if not isinstance(milestones, list):
                        milestones = []

                    # Keep the version heading together and visually distinct.
                    if pdf.get_y() > pdf.h - pdf.b_margin - 20:
                        pdf.add_page()
                    card_x = pdf.l_margin
                    card_w = pdf.w - pdf.l_margin - pdf.r_margin
                    header_y = pdf.get_y() + 1
                    pdf.set_fill_color(235, 247, 239)
                    pdf.set_draw_color(190, 220, 201)
                    pdf.rect(card_x, header_y, card_w, 9, style="DF")
                    pdf.set_xy(card_x + 3, header_y + 1.5)
                    pdf.set_font("Helvetica", "B", 9)
                    pdf.set_text_color(20, 92, 55)
                    pdf.cell(card_w - 34, 6, self._safe_text(f"VERSION {version_number}"))
                    if is_current:
                        pdf.set_xy(card_x + card_w - 31, header_y + 1.5)
                        pdf.set_font("Helvetica", "B", 7)
                        pdf.set_text_color(17, 105, 62)
                        pdf.cell(28, 6, "CURRENT", align="R")
                    pdf.set_y(header_y + 11)
                    pdf.set_text_color(35, 43, 55)

                    raw_reason = str(version.get("reason") or "initial_plan").strip()
                    reason_key = raw_reason.lower().replace(" ", "_")
                    reason_label = reason_labels.get(
                        reason_key,
                        raw_reason.replace("_", " ").strip().capitalize() or "Plan updated",
                    )
                    self._key_value(pdf, "Change", reason_label)

                    page_title = version.get("page_title")
                    if page_title:
                        self._key_value(pdf, "Inspected page", page_title)
                    page_url = version.get("page_url")
                    if page_url:
                        self._key_value(pdf, "Page URL", self._safe_url(page_url))
                    created_at = version.get("created_at")
                    if created_at:
                        try:
                            created_label = datetime.fromtimestamp(float(created_at)).strftime("%Y-%m-%d %H:%M:%S")
                            self._key_value(pdf, "Recorded", created_label)
                        except (TypeError, ValueError, OSError, OverflowError):
                            pass

                    if milestones:
                        pdf.set_font("Helvetica", "B", 8.5)
                        pdf.set_text_color(65, 105, 80)
                        self._paragraph(pdf, "PLAN STEPS", 4.2)
                        for milestone_index, milestone in enumerate(milestones, start=1):
                            safe_milestone = self._sanitize_decision_explanation(milestone)
                            if not safe_milestone:
                                continue
                            pdf.set_font("Helvetica", "", 8.5)
                            pdf.set_text_color(35, 43, 55)
                            self._paragraph(pdf, f"{milestone_index:02d}.  {safe_milestone}", 4.5)
                    else:
                        pdf.set_font("Helvetica", "I", 8)
                        pdf.set_text_color(110, 120, 115)
                        self._paragraph(pdf, "No milestone details were recorded for this version.", 4.2)

                    # Subtle divider between version records.
                    pdf.ln(2)
                    divider_y = pdf.get_y()
                    pdf.set_draw_color(215, 226, 218)
                    pdf.line(card_x, divider_y, card_x + card_w, divider_y)
                    pdf.ln(4)

            self._section(pdf, "Execution Timeline")
            if not steps:
                self._paragraph(pdf, "No execution steps were recorded.", 5)

            for step in steps:
                action = getattr(step, "action", "unknown")
                action = action.value if hasattr(action, "value") else str(action)
                step_number = getattr(step, "step_number", "?")
                error = getattr(step, "error", None)
                is_approval = bool(
                    getattr(step, "approval_required", False)
                    or getattr(step, "human_intervention_needed", False)
                    or "approval" in action.lower()
                )
                if pdf.get_y() > pdf.h - 42:
                    pdf.add_page()
                if error:
                    pdf.set_fill_color(255, 235, 235)
                    pdf.set_text_color(150, 30, 30)
                elif is_approval:
                    pdf.set_fill_color(254, 243, 199)
                    pdf.set_text_color(180, 83, 9)
                else:
                    pdf.set_fill_color(226, 246, 234)
                    pdf.set_text_color(17, 105, 62)
                pdf.set_font("Helvetica", "B", 10)
                label = f"STEP {step_number} | {action.upper()}"
                if error:
                    label += " | ERROR"
                elif is_approval:
                    label += " | HUMAN REVIEW"
                # Wrap unusually long action names instead of letting the header
                # extend past the right margin.
                pdf.set_x(pdf.l_margin)
                self._paragraph(pdf, label, 6)
                pdf.set_text_color(35, 43, 55)
                pdf.set_font("Helvetica", "", 9)

                self._key_value(pdf, "Action", getattr(step, "description", ""))
                decision_explanation = getattr(step, "decision_explanation", None) or getattr(step, "reasoning", None)
                if decision_explanation:
                    self._key_value(pdf, "AI Decision", self._sanitize_decision_explanation(decision_explanation))
                timestamp = getattr(step, "timestamp", None)
                if timestamp:
                    try:
                        self._key_value(pdf, "Time", datetime.fromtimestamp(timestamp).strftime("%H:%M:%S"))
                    except (TypeError, ValueError, OSError, OverflowError):
                        pass
                duration_ms = getattr(step, "duration_ms", None)
                if duration_ms is not None:
                    duration_seconds = max(0.0, float(duration_ms) / 1000.0)
                    if duration_seconds >= 60:
                        minutes = int(duration_seconds // 60)
                        seconds = duration_seconds - (minutes * 60)
                        duration_label = f"{minutes} min {seconds:.1f} sec"
                    elif duration_seconds >= 1:
                        duration_label = f"{duration_seconds:.2f} sec"
                    else:
                        duration_label = f"{float(duration_ms):.0f} ms"
                    self._key_value(pdf, "Duration", duration_label)
                url = self._safe_url(getattr(step, "url", None))
                if url:
                    self._key_value(pdf, "Page", url)
                if getattr(step, "extracted_data", None) is not None:
                    self._key_value(pdf, "Step result", self._sanitize_step_data(getattr(step, "extracted_data")))
                if error:
                    pdf.set_text_color(160, 25, 25)
                    self._key_value(pdf, "Error", self._sanitize_decision_explanation(error))
                    pdf.set_text_color(35, 43, 55)
                if is_approval:
                    pdf.set_text_color(140, 85, 15)
                    self._paragraph(pdf, "Human approval or intervention was part of this step.", 5)
                    pdf.set_text_color(35, 43, 55)

                image_path = self._resolve_screenshot_path(step)
                if image_path:
                    try:
                        from PIL import Image
                        with Image.open(image_path) as screenshot:
                            image_w, image_h = screenshot.size
                        image_w = max(1, float(image_w))
                        image_h = max(1, float(image_h))
                        max_w, max_h = pdf.w - pdf.l_margin - pdf.r_margin, 72
                        scale = min(max_w / image_w, max_h / image_h)
                        draw_w, draw_h = image_w * scale, image_h * scale
                        if pdf.get_y() + draw_h + 8 > pdf.h - pdf.b_margin:
                            pdf.add_page()
                        pdf.set_font("Arial", "I", 8)
                        pdf.set_text_color(91, 112, 100)
                        pdf.cell(0, 5, "Screenshot evidence", new_x="LMARGIN", new_y="NEXT")
                        image_y = pdf.get_y()
                        pdf.image(image_path, x=pdf.l_margin, y=image_y, w=draw_w, h=draw_h)
                        pdf.set_y(image_y + draw_h + 2)
                        pdf.set_text_color(35, 43, 55)
                    except Exception as exc:
                        self._paragraph(pdf, f"[Screenshot could not be embedded: {exc}]", 4)
                pdf.ln(4)

            self._section(pdf, "Report Notes")
            self._paragraph(
                pdf,
                f"This report reflects the task status recorded by the agent ({status}). "
                "It is generated from task metadata and recorded browser actions. "
                "A terminal status is not independent proof of an external effect "
                "such as email delivery unless the execution evidence explicitly verifies it.",
                5,
            )
            pdf_bytes = bytes(pdf.output())
            elapsed_ms = (time.perf_counter() - started) * 1000
            logger.info("PDF generation succeeded: task_id=%s pages=%s size_bytes=%d duration_ms=%.1f", task_id, pdf.page_no(), len(pdf_bytes), elapsed_ms)
            return pdf_bytes
        except Exception:
            elapsed_ms = (time.perf_counter() - started) * 1000
            logger.exception("PDF generation failed: task_id=%s duration_ms=%.1f", task_id, elapsed_ms)
            raise

    @staticmethod
    def _sanitize_decision_explanation(value: Any) -> str:
        """Render a concise, audit-friendly rationale without exposing secrets or raw chain-of-thought."""
        if value is None:
            return ""
        text = str(value).strip()
        if not text:
            return ""
        try:
            from backend.security import redact_text, sanitize_user_facing_error, strip_internal_placeholders
            text = redact_text(text, mask_tier3=True)
            text = sanitize_user_facing_error(text) or ""
            text = strip_internal_placeholders(text, replacement="[protected]")
        except Exception:
            pass
        import re
        text = re.sub(
            r"(?i)\b(password|passwd|api[_ -]?key|access[_ -]?token|authorization|secret|cvv|pin)\b\s*[:=]\s*[^,;\s]+",
            r"\1=[protected]",
            text,
        )
        text = re.sub(r"\s+", " ", text)
        if len(text) > 600:
            text = text[:597].rstrip() + "..."
        return text

    @staticmethod
    def _sanitize_step_data(data: Any) -> str:
        """Redact credential-like fields recursively before report serialization."""
        try:
            from backend.security import redact_sensitive_data, strip_internal_placeholders
            sanitized = redact_sensitive_data(data, mask_tier3=True)
            dumped = json.dumps(sanitized, ensure_ascii=False, default=str)
            return strip_internal_placeholders(dumped, replacement="[protected]")
        except Exception:
            pass

        import re
        sensitive_key = re.compile(
            r"(?i)(password|passwd|secret|token|api[_-]?key|authorization|cookie|"
            r"session|credential|cvv|cvc|pin|private[_-]?key)"
        )
        assignment = re.compile(
            r"(?i)\b(password|passwd|secret|token|api[_ -]?key|authorization|"
            r"cookie|credential|cvv|cvc|pin)\b\s*[:=]\s*([^,;\s]+)"
        )

        def clean(value: Any, key: str = "") -> Any:
            if key and sensitive_key.search(key):
                return "[REDACTED]"
            if isinstance(value, dict):
                return {str(k): clean(v, str(k)) for k, v in value.items()}
            if isinstance(value, (list, tuple, set)):
                return [clean(item) for item in value]
            if isinstance(value, str):
                return assignment.sub(lambda match: f"{match.group(1)}=[REDACTED]", value)
            return value

        try:
            return json.dumps(clean(data), ensure_ascii=False, default=str)
        except Exception:
            return str(clean(str(data)))

    # Backward-compatible method name used by TaskManager.
    generate_pdf_report = generate_report
